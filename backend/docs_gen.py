ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "generated"
CARDS = ROOT / "backend" / "ml" / "model_cards"
HEADER = "<!-- Generated by `make docs` (backend/docs_gen.py). Do not edit by hand. -->\n\n"

BADGES = {
    "established": "strong construct, standard tasks, usable reliability",
    "moderate": "a real construct, but measurement is noisier or more strategy-dependent",
    "experimental": "shown with wide ranges and a caption, and left out of any overall score",
}
ACS_HOOKS = {
    "V": "verification",
    "A": "autonomy",
    "I": "iteration",
    "C": "clarification",
    "R": "responsible_use",
}


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def yes(flag: bool) -> str:
    return "yes" if flag else "no"


def problems(reg: Registry) -> list[str]:
    """Every field a page needs but the registry or code doesn't give."""
    out: list[str] = []
    for d in reg.dimensions:
        for field in ("plain", "main_metric", "framework", "biases", "sources"):
            if not getattr(d, field):
                out.append(f"dimension {d.id}: no {field}")
    for g in reg.games:
        for field in ("paradigm", "does", "code_source"):
            if not getattr(g, field).strip():
                out.append(f"game {g.id}: no {field}")
        if g.kind == "game" and not g.metrics:
            out.append(f"game {g.id}: no metrics")
    for s in reg.consent.switches:
        if not s.plain.strip():
            out.append(f"consent switch {s.id}: no plain text")
    if abs(sum(acs.WEIGHTS.values()) - 1.0) > 1e-9:
        out.append("acs: weights don't add up to 1")
    measured = acs_measures()
    out += [
        f"acs {k}: not described in backend/acs/events.py" for k in acs.WEIGHTS if k not in measured
    ]
    routes = {(r.path, m) for r in me.router.routes for m in getattr(r, "methods", ())}
    out += [f"data rights: no {m} {p} route" for p, m in RIGHTS if (p, m) not in routes]
    cards = sorted(CARDS.glob("*.md"))
    if not cards:
        out.append("model cards: none in backend/ml/model_cards")
    for path in cards:
        text = path.read_text(encoding="utf-8")
        if not text.startswith("# Model card: "):
            out.append(f"model card {path.name}: no '# Model card: <name>' title")
        for section in ("Limits", "Must not be used for"):
            if f"\n## {section}\n" not in text:
                out.append(f"model card {path.name}: no '## {section}' section")
    return out


# --- dimension pages ---------------------------------------------------------------------------


def dimension_page(reg: Registry, d: Dimension) -> str:
    games = sorted((g for g in reg.games if d.id in g.dims), key=lambda g: (-g.dims[d.id], g.id))
    scored = any(d.id in dims for dims in loading_matrix(reg).values())
    lines = [
        f"# {d.name}\n",
        f"**{d.plain}.** Evidence: **{d.badge}**. In the overall score: {yes(d.in_overall)}. "
        f"Sky group: {d.group}. Frameworks: {', '.join(d.framework)}.\n",
    ]
    if d.style:
        lines.append("Shown as a style, not as better or worse.\n")
    if d.note:
        lines.append(f"> {d.note}\n")
    lines += [
        "## Tasks\n",
        "| Game | Paradigm | Loading | Origin | Reliability | Scoring | Metrics | Playable |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for g in games:
        lines.append(
            f"| {cell(g.name)} (`{g.id}`) | {cell(g.paradigm)} | {g.dims[d.id]:g} | {g.origin} "
            f"| {g.effective_reliability:g} | {g.scoring} | {cell(', '.join(g.metrics) or '-')} "
            f"| {yes(g.available)} |"
        )
    lines += ["", "## Scoring\n", f"- Main metric: {d.main_metric}."]
    if scored:
        lines += [
            f"- Answers faster than {quality.ANTICIPATION_MS:g} ms are anticipations and are "
            "dropped; a round that looks like random clicking gets trust 0 "
            "(`backend/scoring/quality.py`).",
            "- Each answer moves the estimate with weight = loading x reliability x context weight "
            "x trust (`backend/scoring/loadings.py`).",
            "- The skill is a Kalman-Elo estimate on a logit scale, shown as a percentage of a "
            "simulated population with its 80% range "
            "(`backend/scoring/kalman_elo.py`, `norms.py`).",
        ]
        if any(g.scoring == "hshs" for g in games):
            lines.append(
                "- Timed games count an answer as a success when it is right within "
                f"{hshs.REFERENCE_PACE:.0%} of the deadline (`backend/scoring/hshs.py`)."
            )
    else:
        lines.append(
            "- Not an ability estimate: its games are scored as "
            f"{' / '.join(sorted({g.scoring for g in games}))}, so it never enters the skill scale."
        )
    lines += ["- Raw trials are stored, so rounds can be re-scored later.", "\n## Uncertainty\n"]
    if scored:
        norms, fresh = Norms(), kalman_elo.Belief()
        floor = range_floor(fresh, d.id, norms)
        lines += [
            f"- A new estimate starts at sigma = {kalman_elo.SIGMA_START:g} (an 80% range of about "
            f"±{half_range(fresh, d.id, norms):.0f} points) unless skill correlations give a "
            "narrower start (`registry/priors.yaml`).",
            f"- Its variance grows by {kalman_elo.Q_ROUND:g} before each round and by "
            f"{kalman_elo.Q_PER_DAY:g} per day without practice.",
        ]
        reach = [(t, rounds_to_target(fresh, d.id, t, norms)) for t in (10.0, 20.0)]
        lines += [
            f"- From a fresh start, about {n} rounds bring it within ±{t:g} points."
            for t, n in reach
            if n is not None
        ]
        lines.append(
            f"- Practice can't narrow it below about ±{floor:.0f} points in the middle of the "
            "scale, because each round also adds noise (`backend/scoring/goals.py`)."
        )
    else:
        lines.append("- Not on the skill scale; shown with its own range where it is shown.")
    lines += ["\n## Biases and confounds\n", *(f"- {b}" for b in d.biases)]
    lines += [
        "\n## Evidence\n",
        f"Badge: **{d.badge}**, {BADGES[d.badge]}.\n",
        "Sources:\n",
        *(f"- <{s}>" for s in d.sources),
    ]
    return HEADER + "\n".join(lines) + "\n"


# --- ACS --------------------------------------------------------------------------------------


def acs_measures() -> dict[str, str]:
    """Component code -> how it is measured, from the docstring of backend/acs/events.py."""
    doc = acs_events.__doc__ or ""
    found = re.findall(r"^([VAICR])  (.+?)(?=^[VAICR]  |\Z)", doc, re.M | re.S)
    out = {}
    for k, text in found:
        how = " ".join(text.split()).split(": ", 1)[-1]
        out[k] = how[:1].upper() + how[1:]
    return out


def acs_page(reg: Registry) -> str:
    measured = acs_measures()
    lo, hi = acs.INTERVAL
    lines = [
        "# AI Collaboration Score\n",
        "How well a person works with the AI, from 0 to 100, computed from what they do "
        "(`backend/acs/score.py`; design in docs/plan/11).\n",
        "## Formula\n",
        "```",
        f"s_k = (successes_k + {acs.PRIOR:g}) / (opportunities_k + {2 * acs.PRIOR:g})"
        f"    # Beta({acs.PRIOR:g}, {acs.PRIOR:g}) prior",
        "ACS = 100 x sum_k w_k * s_k",
        "```\n",
        "- A new user starts every component at 0.5 with a wide range.",
        f'- A component with fewer than {acs.MIN_OPPORTUNITIES} opportunities shows "not enough '
        'data", and its weight is spread proportionally over the others.',
        f"- The range is the {hi - lo:g}% interval of {acs.DRAWS:,} Monte Carlo draws from the "
        "component posteriors.",
        "\n## Components\n",
        "| Code | Component | Weight | Measured by | Games with this hook |",
        "|---|---|---|---|---|",
    ]
    for code, weight in acs.WEIGHTS.items():
        hooked = [g.id for g in reg.games if ACS_HOOKS[code] in g.acs_hooks]
        lines.append(
            f"| {code} | {ACS_COMPONENT_NAMES[code]} | {weight:.2f} | "
            f"{cell(measured.get(code, '-'))} | {', '.join(f'`{g}`' for g in hooked) or '-'} |"
        )
    lines += [
        "",
        "The weights are a design hypothesis (the brief proposed V 25, A 20, I 20, C 20, R 15). "
        "Verification is raised because over-reliance on AI is the main failure mode (Buçinca et "
        "al. 2021; Lee et al., CHI 2025); clarification is lowered because its opportunities are "
        "the rarest, so its estimate is the noisiest. `backend/acs/sensitivity.py` checks rank "
        "stability under ±5-point weight changes on the simulator.\n",
        "Sources:\n",
        "- <https://www.eecs.harvard.edu/~kgajos/papers/2021/bucinca21trust.pdf>",
        "- <https://sites.psu.edu/digitalshred/2025/03/17/the-impact-of-generative-ai-on-critical-"
        "thinking-self-reported-reductions-in-cognitive-effort-and-confidence-effects-from-a-"
        "survey-of-knowledge-workers-lee-et-al/>",
    ]
    return HEADER + "\n".join(lines) + "\n"


