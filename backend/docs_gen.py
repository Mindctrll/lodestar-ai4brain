# --- model cards ------------------------------------------------------------------------------


def model_cards_page() -> str:
    lines = [
        "# Model cards\n",
        "Each model Najma uses has a card in `backend/ml/model_cards/` with what it does, its "
        "data, its limits and what it must not be used for.\n",
        "| Model | What it does |",
        "|---|---|",
    ]
    for path in sorted(CARDS.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        title = text.splitlines()[0].removeprefix("# Model card: ")
        first = text.split("\n## ", 1)[-1].split("\n", 1)[-1].strip().split("\n\n")[0]
        link = f"../../backend/ml/model_cards/{path.name}"
        lines.append(f"| [{cell(title)}]({link}) | {cell(' '.join(first.split()))} |")
    return HEADER + "\n".join(lines) + "\n"


# --- index and entry point --------------------------------------------------------------------


def index_page(reg: Registry) -> str:
    lines = [
        "# Generated docs\n",
        "Written by `make docs` from the registry and the code; `tests/backend/test_docs_gen.py` "
        "fails if a page is missing a field or out of date.\n",
        "- [AI Collaboration Score](acs.md)",
        "- [Data policy](data-policy.md)",
        "- [Model cards](model-cards.md)\n",
        f"## The {len(reg.dimensions)} skills\n",
        "| Skill | Plain meaning | Evidence | In overall |",
        "|---|---|---|---|",
        *(
            f"| [{d.name}](dimensions/{d.id}.md) | {d.plain} | {d.badge} | {yes(d.in_overall)} |"
            for d in reg.dimensions
        ),
    ]
    return HEADER + "\n".join(lines) + "\n"


def render(reg: Registry) -> dict[Path, str]:
    pages = {OUT / "dimensions" / f"{d.id}.md": dimension_page(reg, d) for d in reg.dimensions}
    pages[OUT / "acs.md"] = acs_page(reg)
    pages[OUT / "data-policy.md"] = data_policy_page(reg)
    pages[OUT / "model-cards.md"] = model_cards_page()
    pages[OUT / "README.md"] = index_page(reg)
    return pages


def stale(pages: dict[Path, str]) -> list[str]:
    """Pages that differ from disk, are missing, or are left over from a removed skill."""
    out = [
        str(p.relative_to(ROOT))
        for p, text in pages.items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    out += [str(p.relative_to(ROOT)) for p in OUT.rglob("*.md") if p not in pages]
    return sorted(out)


def main(argv: list[str]) -> int:
    reg = load_registry()
    missing = problems(reg)
    if missing:
        print("docs: missing fields:\n  " + "\n  ".join(missing))
        return 1
    pages = render(reg)
    if "--check" in argv:
        old = stale(pages)
        if old:
            print("docs: out of date (run `make docs`):\n  " + "\n  ".join(old))
            return 1
        print("docs: up to date")
        return 0
    for p in OUT.rglob("*.md"):
        if p not in pages:
            p.unlink()
    for path, text in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"docs: wrote {len(pages)} pages to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
