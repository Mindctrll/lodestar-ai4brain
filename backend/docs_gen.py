"""Docs from code (docs/plan/16, WP4.3): `make docs` writes docs/generated/ from the registry and
the code's own constants, so the pages can't drift from what the app does.

    uv run python -m backend.docs_gen          # write the pages
    uv run python -m backend.docs_gen --check  # fail if a field is missing or a page is stale

It lists every missing field (a skill with no sources, a game with no paradigm, a model card with
no limits...) and exits 1 instead of writing a page with a hole in it.
"""

