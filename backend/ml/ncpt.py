"""Skill correlations from NCPT (Jaffe et al. 2022, CC BY 4.0; docs/plan/10, "NCPT dataset").

Each NCPT test run gives one person's scores on several subtests. We map subtests to Lodestar's
skills, compute Spearman correlations across test runs pooled over two batteries, and write them to
`registry/priors.yaml`. They are observed-score correlations, so lower than the correlations
between the underlying skills: as priors that errs on the cautious side. No demographic field is
read.

Run with `make ncpt-priors` after `make ml-data`.
"""

import datetime as dt
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

DATA = Path("data/ncpt")
OUT = Path("registry/priors.yaml")
BATTERIES = (17, 32)
# NCPT subtest id -> (skill, sign). Times (go/no-go, trail making) are better when lower.
SUBTESTS: dict[int, tuple[str, int, str]] = {
    27: ("selective_attention", 1, "Divided visual attention"),
    28: ("short_term_memory", 1, "Forward memory span"),
    33: ("working_memory", 1, "Reverse memory span"),
    29: ("numerical_thinking", 1, "Arithmetic reasoning"),
    30: ("verbal_skill", 1, "Grammatical reasoning"),
    31: ("reasoning", 1, "Progressive matrices"),
    38: ("processing_speed", 1, "Digit symbol coding"),
    40: ("cognitive_flexibility", -1, "Trail making part B"),
    32: ("inhibition", -1, "Go/no-go"),
}


def battery_correlations(battery: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Spearman correlations between mapped skills in one battery, and pair counts."""
    d = pd.read_csv(
        DATA / f"battery{battery}_df.csv",
        usecols=["test_run_id", "specific_subtest_id", "raw_score"],
    )
    d = d[d["specific_subtest_id"].isin(SUBTESTS)]
    wide = d.pivot_table(
        index="test_run_id", columns="specific_subtest_id", values="raw_score", aggfunc="first"
    )
    wide = wide.rename(columns={s: SUBTESTS[s][0] for s in wide.columns})
    for skill, sign, _ in SUBTESTS.values():
        if skill in wide and sign < 0:
            wide[skill] = -wide[skill]
    corr = wide.corr(method="spearman")
    present = wide.notna().astype(int)
    pairs = present.T @ present
    return corr, pairs


def pooled() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Fisher-z average of each pair over the batteries that have it, weighted by pair count."""
    zsum: pd.DataFrame | None = None
    wsum: pd.DataFrame | None = None
    for battery in BATTERIES:
        corr, pairs = battery_correlations(battery)
        z = np.arctanh(corr.clip(-0.999, 0.999)) * pairs
        zsum = z if zsum is None else zsum.add(z, fill_value=0)
        wsum = pairs if wsum is None else wsum.add(pairs, fill_value=0)
    assert zsum is not None and wsum is not None
    return np.tanh(zsum / wsum), wsum


def write(path: Path = OUT) -> dict[str, object]:
    corr, counts = pooled()
    skills = list(corr.columns)
    rows = [  # only pairs some test run measured together
        [a, b, round(float(corr.loc[a, b]), 3), int(counts.loc[a, b])]
        for i, a in enumerate(skills)
        for j, b in enumerate(skills)
        if i < j and counts.loc[a, b] > 0 and np.isfinite(corr.loc[a, b])
    ]
    doc: dict[str, object] = {
        "generated": dt.date.today().isoformat(),
        "source": "NCPT, Jaffe et al. 2022, https://zenodo.org/records/7249732 (CC BY 4.0)",
        "batteries": list(BATTERIES),
        "subtests": {skill: name for _, (skill, _, name) in sorted(SUBTESTS.items())},
        "correlations": rows,
    }
    header = (
        "# Skill correlations derived from NCPT test scores (docs/plan/10). Generated by\n"
        "# `make ncpt-priors` (backend/ml/ncpt.py); do not edit by hand. Each row: skill, skill,\n"
        "# Spearman correlation of observed scores, test runs with both. Pairs no battery\n"
        "# measured together are missing. Used for cold-start priors (backend/scoring/priors.py)\n"
        "# and the simulator's population.\n"
    )
    meta = {k: v for k, v in doc.items() if k != "correlations"}
    lines = "".join(f"- [{a}, {b}, {r}, {n}]\n" for a, b, r, n in rows)
    text = header + yaml.safe_dump(meta, sort_keys=False, width=100) + "correlations:\n" + lines
    path.write_text(text, encoding="utf-8")

    return doc


if __name__ == "__main__":
    out = write()
    print(f"wrote {OUT} with {len(out['correlations'])} pairs")  # type: ignore[arg-type]
    sys.exit(0)
