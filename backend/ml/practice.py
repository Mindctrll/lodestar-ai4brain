"""How much people improve with practice, from the Lumosity curves (docs/plan/10, 07).

One fit, written to `registry/practice.yaml`: `gain(k) = a * k^(-b)`, the average change in score
from the k-th session with a kind of game to the next. The Brain Twin adds it after each round as
its prediction step (people improve with practice; the next round's evidence corrects the guess),
and the simulator's people learn at this rate times a personal factor, so the world it tests in
matches the data.

In 98.6% of the data a session holds exactly one play of a game family, so one session here is
one round in Lodestar. Scores are on the population scale of backend/ml/curves.py.
Run with `make practice-prior` after `make ml-data`.
"""

import datetime as dt
from pathlib import Path

import numpy as np
import yaml

from backend.ml import curves

OUT = Path("registry/practice.yaml")
SESSIONS = 30


def mean_gains(c: curves.Curves, sessions: int = SESSIONS) -> np.ndarray:
    lengths = c.lengths()
    out = []
    for k in range(1, sessions + 1):
        ok = np.flatnonzero(lengths > k)
        out.append(float(np.mean(c.score[c.offsets[ok] + k] - c.score[c.offsets[ok] + k - 1])))
    return np.array(out)


def fit(gains: np.ndarray) -> dict[str, float]:
    k = np.arange(1, len(gains) + 1, dtype=np.float64)
    keep = gains > 0
    slope, intercept = np.polyfit(np.log(k[keep]), np.log(gains[keep]), 1)
    return {"a": round(float(np.exp(intercept)), 4), "b": round(float(-slope), 4)}


def write(path: Path = OUT) -> dict[str, object]:
    gains = mean_gains(curves.curves())
    params = fit(gains)
    doc = {
        "generated": dt.date.today().isoformat(),
        "source": "Lumosity learning data, Steyvers & Schafer 2020, https://osf.io/g9zkf/",
        "sessions_fitted": SESSIONS,
        "per_round": {"a": params["a"], "b": params["b"]},
        "observed_mean_gain": [round(float(x), 4) for x in gains],
    }
    header = (
        "# Average improvement with practice, fitted to the Lumosity curves (docs/plan/10).\n"
        "# Generated by `make practice-prior` (backend/ml/practice.py); do not edit by hand.\n"
        "# per_round: average gain from round k to k+1 = a * k^-b, in population SD. Used by the\n"
        "# Brain Twin's prediction step (backend/scoring/rounds.py) and the simulator's learners.\n"
    )
    path.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=100), encoding="utf-8")
    return doc


if __name__ == "__main__":
    print(write())
